#!/usr/bin/env node
// Reconcile readable works, legacy progress keys, anthology membership and the
// older community chart. The checked-in identity file is deliberately stable:
// this script validates it but never regenerates IDs from mutable titles.

import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { loadFromScript, repoRoot } from './load-data.mjs';
import { normaliseTitle, chartTitleKey } from './chart-match.mjs';

const readJson = (file) => JSON.parse(readFileSync(join(repoRoot, file), 'utf8'));
const { bookData } = loadFromScript(['bookData']);
const { identities } = readJson('data/work-identities.json');
const chart = readJson('daunt-chart.json');
const publisherCollections = readJson('data/publisher-collections.json');
const reportPath = join(repoRoot, 'CATALOGUE_AUDIT.md');
const errors = [];

const byKey = new Map();
const byId = new Map();
for (const identity of identities) {
    if (byId.has(identity.id)) errors.push(`Repeated work ID: ${identity.id}`);
    byId.set(identity.id, identity);
    if (!identity.legacyKeys?.length || !identity.legacyKeys.includes(identity.id)) {
        errors.push(`${identity.id} needs its canonical key in legacyKeys`);
    }
    for (const key of identity.legacyKeys ?? []) {
        if (byKey.has(key)) errors.push(`Entry ${key} maps to multiple works`);
        byKey.set(key, identity.id);
        const book = bookData[key];
        if (!book) errors.push(`Identity ${identity.id} references absent entry ${key}`);
        else if (book.title !== identity.title) {
            errors.push(`${key} title differs from work ${identity.id}: ${book.title}`);
        }
    }
}
for (const key of Object.keys(bookData)) {
    if (!byKey.has(key)) errors.push(`Entry ${key} has no work identity`);
}

if (errors.length) {
    for (const error of errors) console.error(`ERROR: ${error}`);
    process.exit(1);
}

const workByTitle = new Map();
for (const identity of identities) {
    const title = normaliseTitle(identity.title);
    if (!workByTitle.has(title)) workByTitle.set(title, identity.id);
}

const chartMatches = new Set();
const chartCandidates = [];
for (const node of chart.nodes) {
    if (node.isAnthologyContainer) continue;
    const id = workByTitle.get(chartTitleKey(node.label));
    if (id) chartMatches.add(id);
    else chartCandidates.push(node.label);
}

const collections = new Map();
for (const [key, book] of Object.entries(bookData)) {
    if (!book.anthology) continue;
    if (!collections.has(book.anthology)) collections.set(book.anthology, new Set());
    collections.get(book.anthology).add(byKey.get(key));
}

const reprints = identities.filter((identity) => identity.legacyKeys.length > 1);
const lines = [
    '# Catalogue reconciliation',
    '',
    '> Generated by `node tools/reconcile-catalogue.mjs`. Edit `data/work-identities.json` to change a work identity, then regenerate. This report is an identity audit, not a claim that every publication fact has been verified.',
    '',
    `- Catalogue entries: **${Object.keys(bookData).length}**`,
    `- Distinct work identities: **${identities.length}**`,
    `- Reprint entry groups: **${reprints.length}**`,
    `- Named collection or novelisation groups represented by component entries: **${collections.size}**`,
    `- Collections checked against a publisher contents page: **${Object.keys(publisherCollections.collections).length}** (${Object.values(publisherCollections.collections).reduce((sum, record) => sum + record.entries.length, 0)} entries)`,
    `- Distinct works matched to chart nodes by title or recorded alias: **${chartMatches.size}**`,
    `- Chart nodes without a title match: **${chartCandidates.length}**, requiring editorial reconciliation`,
    '',
    '## Reprints represented more than once',
    '',
    '| Work ID | Title | Existing entry keys |',
    '| --- | --- | --- |',
    ...reprints.map((work) => `| \`${work.id}\` | ${work.title} | ${work.legacyKeys.map((key) => `\`${key}\``).join(', ')} |`),
    '',
    'Both keys remain valid for old reading records. The catalogue counts each group once in work-level progress and keeps both legacy statuses in sync.',
    '',
    '## Anthology containers',
    '',
    '| Group | Distinct listed works | Publisher review |',
    '| --- | ---: | --- |',
    ...[...collections].sort(([a], [b]) => a.localeCompare(b))
        .map(([name, workIds]) => {
            const checked = publisherCollections.collections[name];
            const disputed = publisherCollections.disputed?.[name];
            const relation = Object.values(bookData).find((book) => book.anthology === name)?.collectionRelation;
            const status = checked ? `[Contents checked](${checked.source})`
                : disputed ? `[Disputed listing](${disputed.publisherSource})`
                : relation === 'novelised in' ? 'Novelisation, not a reprint collection' : 'Pending';
            return `| ${name} | ${workIds.size} | ${status} |`;
        }),
    '',
    `These counts describe current catalogue membership. Linked publisher contents, titles and authors were checked on ${publisherCollections.reviewedAt}; other rows remain unverified. No row certifies current edition availability. The same work may appear in more than one collection.`,
    '',
    'The current Black Library *Mark of Calth* product page lists seven stories and omits *Athame*. A [bibliographic record](https://obnb.uk/p16417052-mark-of-calth) lists *Athame* as an eighth. The published book contents need checking before this group is marked verified. Black Library describes *Garro* as a novelisation of the component audio dramas and novella, not a verbatim anthology.',
    '',
    '## Chart nodes needing review',
    '',
    'This is a title-matching queue, not an automatic import list. The [publisher review](CHART_RECONCILIATION.md) records evidence and spelling or format disputes for all 19 candidates. None has been imported yet.',
    '',
    ...chartCandidates.sort((a, b) => a.localeCompare(b)).map((title) => `- ${title}`),
    '',
];
const report = lines.join('\n');

if (process.argv.includes('--check')) {
    if (readFileSync(reportPath, 'utf8') !== report) {
        console.error('CATALOGUE_AUDIT.md is stale. Run node tools/reconcile-catalogue.mjs');
        process.exit(1);
    }
    console.log(`Identity audit passed: ${identities.length} works, ${Object.keys(bookData).length} entries.`);
} else {
    writeFileSync(reportPath, report);
    console.log(`Wrote CATALOGUE_AUDIT.md: ${identities.length} works, ${Object.keys(bookData).length} entries.`);
}
