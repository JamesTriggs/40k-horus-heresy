#!/usr/bin/env node
// Generates ORDERING_DECISIONS.md from bookData.
//
// Run with: node tools/generate-ordering-doc.mjs
//
// The document used to be maintained by hand alongside the data, and the two
// drifted until they disagreed in 212 of 213 places. It is now derived, so the
// only way to change the order is to change the data. validate-data.mjs then
// asserts that the two still agree.

import { writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { loadFromScript, repoRoot as root } from './load-data.mjs';


const { bookData } = loadFromScript(['bookData']);
const entries = Object.entries(bookData);

const ANTHOLOGIES = [
    ['Tales of Heresy', 'X'],
    ['Age of Darkness', 'XVI'],
    ['The Primarchs', 'XX'],
    ['Shadows of Treachery', 'XXII'],
    ['Mark of Calth', 'XXV'],
    ['Legacies of Betrayal', 'XXXI'],
    ['War Without End', 'XXXIII'],
    ['Eye of Terra', 'XXXV'],
    ['The Silent War', 'XXXVII'],
    ['Corax', 'XL'],
    ['Garro', 'XLII'],
    ['Shattered Legions', 'XLIII'],
    ['Tallarn', 'XLV'],
    ['The Burden of Loyalty', 'XLVIII'],
    ['Born of Flame', 'L'],
    ['Heralds of the Siege', 'LII'],
];

const today = new Date().toISOString().slice(0, 10);

const lines = [];
const w = (s = '') => lines.push(s);

w('# Horus Heresy Chronological Ordering Decision Log');
w();
w('**Generated:** ' + today + ' by `tools/generate-ordering-doc.mjs`  ');
w('**Total Books:** ' + entries.length + '  ');
w('**Purpose:** Authoritative chronological ordering for all Horus Heresy books and anthology stories.');
w();
w('> Do not edit this file by hand. It is derived from `bookData` in `script.js`.');
w('> To change the order, change the order of the keys in `bookData`, then regenerate.');
w('> `tools/validate-data.mjs` asserts that this file and the rendered order agree.');
w();
w('---');
w();
w('## Ordering Principles');
w();
w('1. **Strict in-universe chronology.** Books are ordered by their in-universe date, with no exceptions carved out for any series.');
w('2. **Range handling.** A book covering a span (for example `007-009.M31`) sorts at the start of that span.');
w('3. **Narrative present, not earliest content.** A book framed late that flashes back sorts at its frame, because that is when it can be read without being spoiled. This is why several of The Primarchs novels sort later than the events they depict.');
w('4. **Simultaneous events.** Where two books share a date, the curated sequence is preserved: main novels first, then anthology stories, then character series.');
w();
w('Principle 1 replaces an earlier principle that placed pre-Heresy books at the end as supplemental material. That contradicted strict chronology, and the two could not both hold.');
w();
w('---');
w();
w('## Key Chronological Events Reference');
w();
w('| Timeline | Event | Key Books |');
w('|----------|-------|-----------|');

// The event names are editorial, but the dates are looked up from the data.
// They used to be hardcoded here, and after the research pass corrected 30
// timelines, 8 of 15 rows were quietly wrong. A summary table that disagrees
// with the list beneath it is worse than no table.
const KEY_EVENTS = [
    ['Caliban Era', ['DESCENT OF ANGELS']],
    ['Razing of Monarchia', ['THE FIRST HERETIC']],
    ['Council of Nikaea', ['A THOUSAND SONS']],
    ['Horus at his zenith', ['HORUS RISING']],
    ['Horus corrupted on Davin', ['FALSE GODS']],
    ['Burning of Prospero', ['PROSPERO BURNS']],
    ['Isstvan III', ['GALAXY IN FLAMES']],
    ['Isstvan V Drop Site Massacre', ['FULGRIM', 'THE PHOENICIAN']],
    ['Battle of Calth', ['KNOW NO FEAR']],
    ['Shadow Crusade', ['BETRAYER']],
    ['Battle of Molech', ['VENGEFUL SPIRIT']],
    ['Imperium Secundus', ['THE UNREMEMBERED EMPIRE']],
    ['Beta-Garmon', ['TITANDEATH', 'WOLFSBANE']],
    ['Siege of Terra', ['THE SOLAR WAR', 'THE END AND THE DEATH: VOLUME III']],
    ['The Scouring', ['KONRAD CURZE: THE NIGHT HAUNTER']],
];

const byTitle = new Map(entries.map(([, b]) => [b.title.toUpperCase(), b]));

// Parse a timeline into an absolute start and end year, so an event covering
// several books can be reported as one continuous span.
const parseTimeline = (timeline) => {
    const m = /^(\d{3})(?:-(\d{3}))?\.M(\d{2})$/.exec(timeline || '');
    if (!m) return null;
    const millennium = Number(m[3]);
    const base = (millennium - 1) * 1000;
    return {
        start: base + Number(m[1]),
        end: base + Number(m[2] ?? m[1]),
        millennium,
    };
};

const formatSpan = (start, end) => {
    const toParts = (absolute) => ({
        millennium: Math.floor(absolute / 1000) + 1,
        year: String(absolute % 1000).padStart(3, '0'),
    });
    const a = toParts(start);
    const b = toParts(end);
    if (start === end) return `${a.year}.M${a.millennium}`;
    if (a.millennium === b.millennium) return `${a.year}-${b.year}.M${a.millennium}`;
    return `${a.year}.M${a.millennium} to ${b.year}.M${b.millennium}`;
};

const eventRows = KEY_EVENTS.map(([event, titles]) => {
    const books = titles.map((t) => {
        const book = byTitle.get(t);
        if (!book) throw new Error(`Key event "${event}" names a book not in bookData: ${t}`);
        const parsed = parseTimeline(book.timeline);
        if (!parsed) throw new Error(`Key event "${event}" names ${t}, whose timeline does not parse: ${book.timeline}`);
        return { book, parsed };
    });

    const start = Math.min(...books.map((b) => b.parsed.start));
    const end = Math.max(...books.map((b) => b.parsed.end));

    return {
        timeline: formatSpan(start, end),
        event,
        // Titles are stored in caps and shown that way throughout the list
        // below, so leave them alone rather than title-casing "VOLUME III".
        books: books.map((b) => b.book.title).join(', '),
        sort: start,
    };
});

eventRows.sort((a, b) => a.sort - b.sort);
eventRows.forEach((r) => w(`| ${r.timeline} | ${r.event} | ${r.books} |`));

w();
w('---');
w();
w('## Complete Chronological Book List');
w();
w('Books are listed in the order the site renders them.');
w();

let currentTimeline = null;
entries.forEach(([, book], index) => {
    if (book.timeline !== currentTimeline) {
        currentTimeline = book.timeline;
        w();
        w('### Timeline: ' + currentTimeline);
        w();
    }
    w(`**${index + 1}.** [${book.number}] **${book.title.replace(/\*/g, '')}**`);
    w();
});

w('---');
w();
w('## Anthology Volume Reference');
w();
w('Anthology volumes are represented by their component stories rather than by a single entry, so the volume numbers below do not appear as books in the list.');
w();
const counts = new Map();
for (const [, book] of entries) {
    if (book.anthology) counts.set(book.anthology, (counts.get(book.anthology) ?? 0) + 1);
}
for (const [name, numeral] of ANTHOLOGIES) {
    const n = counts.get(name);
    if (n) w(`- **${name} (${numeral})**: ${n} stories`);
}
const unlisted = [...counts.keys()].filter((k) => !ANTHOLOGIES.some(([n]) => n === k));
for (const name of unlisted) w(`- **${name}**: ${counts.get(name)} stories`);
w();
w('---');
w();
w('## Sources & Research');
w();
w('- [Horus Heresy Timeline - Lexicanum](https://wh40k.lexicanum.com/wiki/Horus_Heresy_Timeline)');
w('- [Chronological Reading Order - Adeptus Ars](https://www.adeptusars.com/features/the-horus-heresy-books-in-chronological-order)');
w('- [Complete Reading Order - TL Branson](https://www.tlbranson.com/horus-heresy-reading-order/)');
w();
w('Dates for The Primarchs series, the two previously undated anthology stories, and the re-anchoring of The Master of Mankind are recorded with per-entry sources and confidence in `tools/proposed-dates.json`.');
w();

writeFileSync(join(root, 'ORDERING_DECISIONS.md'), lines.join('\n'));
console.log(`Wrote ORDERING_DECISIONS.md, ${entries.length} entries.`);
